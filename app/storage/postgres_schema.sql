CREATE TABLE IF NOT EXISTS historical_matches (
    id TEXT PRIMARY KEY,
    source TEXT NOT NULL,
    source_match_id TEXT NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    team_a_name TEXT NOT NULL,
    team_b_name TEXT NOT NULL,
    team_a_source_id TEXT,
    team_b_source_id TEXT,
    winner_name TEXT,
    winner_source_id TEXT,
    winner_side TEXT CHECK (winner_side IN ('team_a', 'team_b')),
    tournament_name TEXT,
    tournament_source_id TEXT,
    league_name TEXT,
    league_source_id TEXT,
    series_name TEXT,
    series_source_id TEXT,
    raw_stage_label TEXT,
    competitive_stage TEXT NOT NULL DEFAULT 'unknown',
    normalized_round TEXT NOT NULL DEFAULT 'unknown',
    best_of INTEGER,
    status TEXT NOT NULL DEFAULT 'unknown',
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source, source_match_id)
);
